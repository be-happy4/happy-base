    public static boolean equalsAny(String string, final String... searchStrings) {
        if (ArrayUtils.isNotEmpty(searchStrings)) {
            for (var next : searchStrings) {
                if (Objects.equals(string, next)) {
                    return true;
                }
            }
        }
        return false;
    }

